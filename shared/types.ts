  frame_ref: string;
  status: "identified" | "unidentified" | "needs_appraisal";
  title: string;
  author: string;
  publisher: string;
  edition: string;
  isbn: string;
  spine_height_cm: number | null;
  spine_thickness_cm: number | null;
  id_confidence: number;
  replacement_cost: Price;
  used_value: Price;
  quad: Quad;
  visible_text: string;
  rare_indicators: string[];
