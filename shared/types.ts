export type Point = { x: number; y: number };
export type Quad = [Point, Point, Point, Point];
export type FrameRecord = {
  id: string;
  frame_ref: string;
  captured_at: string;
  width: number;
  height: number;
  shelf_id: string;
  sequence: number;
  quality?: {
    blur: number;
    glare: number;
    sharpness?: number;
    brightness?: number;
  };
  analysis_status: "queued" | "processing" | "done" | "failed" | "skipped";
  error?: string;
};
export type Calibration = {
  id: string;
  frame_ref: string;
  plane: "shelf" | "floor" | "wall";
  shelf_id?: string;
  width_cm: number;
  height_cm: number;
  quad: Quad;
};
export type Price = {
  amount: number | null;
  source: string;
  url: string;
  retrieved_at: string;
  converted: boolean;
  condition_assumed: string;
  currency: string;
  original_amount?: number;
  original_currency?: string;
  fx_source?: string;
  fx_rate?: number;
  evidence_ref?: string;
  notes?: string;
};
